/**
 * CyberScape domain constants.
 *
 * The infrastructure atlas is the single source of truth for the client, the API,
 * and the tests. Every tracked asset carries the same six comparable metrics so
 * that resilience, capacity, and exposure stay meaningful across the network.
 */

export interface CatalogMetric {
  key: string;
  label: string;
  unit: string;
  format: 'number' | 'percent' | 'compact';
  higherIsBetter: boolean;
  /** Upper bound used by compact metric bars and client previews. */
  max?: number;
}

export interface CatalogEntity {
  id: string;
  name: string;
  category: Category;
  region: Region;
  status: EntityStatus;
  summary: string;
  metrics: Record<string, number>;
  tags: string[];
}

export interface SimulationAction {
  id: string;
  label: string;
  description: string;
  severity: 'low' | 'medium' | 'high' | 'critical';
}

